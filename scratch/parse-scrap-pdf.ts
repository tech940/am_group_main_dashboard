function parsePdfData() {
  const p1Lines = page1Text.trim().split('\n').filter(Boolean)
  const p2Lines = page2Text.trim().split('\n').filter(Boolean)

  console.log(`Page 1 line count: ${p1Lines.length}, Page 2 line count: ${p2Lines.length}`)

  const transactions: any[] = []

  for (let i = 0; i < p1Lines.length; i++) {
    const p1Cols = p1Lines[i].split('\t').map(c => c.trim())
    const p2Cols = (p2Lines[i] || '').split('\t').map(c => c.trim())

    // P1 columns:
    // 0: Timestamp, 1: LOCATION, 2: Department, 3: SCRAP TYPE, 4: DESCRIPTION, 5: Rate, 6: SOLD BY, 7: SOLD TO, 8: SOLD DATE, 9: TOTAL AMOUNT, 10: PAYMENT HANDOVER TO, 11: WEIGHT QTY
    const rawTimestamp = p1Cols[0] || '2026-04-01 00:00:00'
    const locationName = p1Cols[1] || 'JAMMU AUTO MART - CHANNI RAMA'
    const departmentName = (p1Cols[2] || 'SERVICE').toUpperCase()
    const scrapTypeName = p1Cols[3] || 'PLASTIC'
    const description = p1Cols[4] || ''
    const ratePerUnit = parseFloat((p1Cols[5] || '0').replace(/,/g, '')) || 0
    const soldByName = p1Cols[6] || 'SHIKHA'
    const soldTo = p1Cols[7] || 'LOCAL VENDOR'
    const rawSoldDate = p1Cols[8] || rawTimestamp.split(' ')[0]
    const calculatedTotal = parseFloat((p1Cols[9] || '0').replace(/,/g, '')) || 0
    const paymentHandoverToName = p1Cols[10] || 'CASH HANDOVER TO MD'
    const weightQty = parseFloat((p1Cols[11] || '0').replace(/,/g, '')) || 0

    // P2 columns:
    // 0: AMOUNT RECEIVED, 1: Mode of payment, 2: Remarks (optional), 3: GROUP
    const amountReceived = parseFloat((p2Cols[0] || p1Cols[9] || '0').replace(/,/g, '')) || 0
    const paymentModeName = (p2Cols[1] || 'ONLINE').toUpperCase()
    const groupName = p2Cols[p2Cols.length - 1] || 'JAM'
    const remarks = p2Cols.length > 3 ? p2Cols[2] : ''

    const outstandingAmount = Math.max(0, calculatedTotal - amountReceived)

    // Convert date string to ISO
    let soldDateIso = '2026-04-01'
    try {
      const parts = rawSoldDate.split(/[\/\-\,\s]+/)
      if (parts.length >= 3) {
        let m = parts[0].padStart(2, '0')
        let d = parts[1].padStart(2, '0')
        let y = parts[2]
        if (y.length === 2) y = '20' + y
        soldDateIso = `${y}-${m}-${d}`
      }
    } catch (e) {
      soldDateIso = '2026-04-01'
    }

    const txId = `tx-pdf-${1000 + i}`
    const txNo = `SCRAP-2026-${String(i + 1).padStart(4, '0')}`

    transactions.push({
      id: txId,
      transactionNumber: txNo,
      timestamp: `${soldDateIso}T10:00:00Z`,
      groupId: `grp-${groupName.toLowerCase().replace(/[^a-z0-9]/g, '')}`,
      groupName: groupName,
      locationId: `loc-${locationName.toLowerCase().replace(/[^a-z0-9]/g, '')}`,
      locationName: locationName,
      departmentId: `dept-${departmentName.toLowerCase().replace(/[^a-z0-9]/g, '')}`,
      departmentName: departmentName,
      scrapTypeId: `st-${scrapTypeName.toLowerCase().replace(/[^a-z0-9]/g, '')}`,
      scrapTypeName: scrapTypeName,
      unit: description === 'LITER' ? 'Ltr' : description === 'PIECES' ? 'Pcs' : 'Kg',
      description: description,
      weightQty: weightQty,
      ratePerUnit: ratePerUnit,
      calculatedTotal: calculatedTotal,
      amountReceived: amountReceived,
      outstandingAmount: outstandingAmount,
      soldById: `emp-1`,
      soldByName: soldByName,
      soldTo: soldTo,
      soldDate: soldDateIso,
      paymentModeId: `pm-1`,
      paymentModeName: paymentModeName,
      paymentHandoverToId: `ho-1`,
      paymentHandoverToName: paymentHandoverToName,
      remarks: remarks || undefined,
      status: outstandingAmount > 0 ? 'FLAGGED' : 'COMPLETED',
      attachments: [],
      createdAt: `${soldDateIso}T10:00:00Z`,
      updatedAt: `${soldDateIso}T10:00:00Z`
    })
  }

  console.log(`Parsed ${transactions.length} transactions successfully.`)
  const grandTotal = transactions.reduce((acc, t) => acc + t.calculatedTotal, 0)
  const totalReceived = transactions.reduce((acc, t) => acc + t.amountReceived, 0)
  const totalOutstanding = transactions.reduce((acc, t) => acc + t.outstandingAmount, 0)
  console.log(`Grand Total Revenue: ₹${grandTotal.toLocaleString()}`)
  console.log(`Total Received: ₹${totalReceived.toLocaleString()}`)
  console.log(`Total Outstanding: ₹${totalOutstanding.toLocaleString()}`)

  return transactions
}

