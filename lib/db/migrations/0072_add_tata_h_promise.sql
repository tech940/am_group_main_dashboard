  reg_no_key                    text GENERATED ALWAYS AS (upper(regexp_replace(reg_no, '[^A-Za-z0-9]', '', 'g'))) STORED,

  model                         text NOT NULL,
  colour                        text,
  manufacturing_year            smallint,
  odometer_km                   integer,
  engine_no                     text,
  chassis_no                    text,
