-- 0072 — AM Tata "H Promise": the pre-owned car desk (purchase → booking → sale → paperwork → approvals → ledger).
--
-- ⚠️ APPLY BY HAND ON THE DIRECT/SESSION PORT 5432 (scripts/apply-migration-0072.ts). DDL must not run on the
--    pgbouncer pooler (6543).
--
-- ── Why this exists (owner decisions, 2026-09-17) ───────────────────────────────────────────────
-- AM Tata ran its used-car business in a Google Apps Script web app over one Google Sheet. H Promise replaces it.
-- The sheet kept everything in one 69-column row and reused columns for two things (the booking date was written
-- into a column the sale form also wrote, and the MIS read the booking RECEIPT column as a date). Here:
--
--   tata_h_promise_vehicles         one row per vehicle lifecycle: purchase, sale, paperwork, both approvals
--   tata_h_promise_bookings         bookings in their own table, so book → refund → rebook is possible
--   tata_h_promise_files            every uploaded file; replacing one keeps the old row (superseded_at)
--   tata_h_promise_events           append-only history: who changed what, when
--   tata_h_promise_options          the editable name lists (staff, WhatsApp approvers, locations)
--   tata_h_promise_settings         effective-dated rates for the profit/interest formulas
--   tata_h_promise_exchange_bonuses the small exchange-bonus register the sheet kept on its own tab
--
-- House rules followed: status columns are free TEXT (0050) — a new value never needs a migration and never
-- becomes an enum outage. Money is numeric(14,2). The lifecycle stage (in stock / booked / sold) is DERIVED in
-- lib/h-promise/stage.ts, never stored, so it cannot disagree with the facts it is derived from. Price with GST
-- is computed, not stored, for the same reason.
--
-- Safeguards the owner chose, enforced HERE as well as in the app, so a future code path cannot skip them:
--   · nobody decides their own entry (CHECK constraints below);
--   · an approved purchase or sale price cannot change until an approver reopens it (trigger below);
--   · full change history (tata_h_promise_events is append-only).

BEGIN;

