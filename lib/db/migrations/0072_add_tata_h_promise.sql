  -- Purchase
  purchase_date                 date NOT NULL,
  purchase_price                numeric(14,2) NOT NULL,
  purchase_gst_pct              numeric(5,2) NOT NULL DEFAULT 0,
  expected_profit               numeric(14,2),
  purchase_remarks              text,
  purchase_financed             boolean NOT NULL DEFAULT false,
  purchased_by                  text NOT NULL,
  sales_consultant              text,
  -- Phone formats are validated by the app (10 digits). Not a CHECK: imported sheet values are kept as found
  -- and reported, rather than silently dropped.
  seller_phone                  text,
  -- Who gave the go-ahead on WhatsApp — an option value, or 'NOT_TAKEN'. A record of the phone call, NOT the
  -- in-app approval below.
  purchase_whatsapp_approver    text NOT NULL,
  purchase_status               text NOT NULL DEFAULT 'pending',       -- pending | approved | rejected
  purchase_submitted_by         uuid REFERENCES public.users (id),
  purchase_submitted_by_name    text,
  purchase_submitted_at         timestamptz,
  purchase_decided_by           uuid REFERENCES public.users (id),
  purchase_decided_by_name      text,
  purchase_decided_at           timestamptz,
  purchase_decision_reason      text,

  -- Sale (one per vehicle lifecycle; a buy-back is a new row)
  sale_status                   text,                                  -- NULL | pending | approved | rejected
  sale_date                     date,
  selling_price                 numeric(14,2),
  other_cost                    numeric(14,2) NOT NULL DEFAULT 0,
  is_demo                       boolean,
  sold_to                       text,                                  -- CUSTOMER | BROKER | SCRAP
  sale_financed                 boolean,
  sold_by                       text,
  buyer_name                    text,
