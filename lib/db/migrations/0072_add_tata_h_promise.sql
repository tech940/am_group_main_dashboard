-- Prices lock once approved (owner decision). Reopening is its own step: approved → pending first, then the edit,
-- then a fresh approval — so the change is visible in the history and needs an approver again.
CREATE OR REPLACE FUNCTION public.tata_h_promise_price_lock()
  RETURNS trigger
  LANGUAGE plpgsql
  SET search_path = ''
AS $$
BEGIN
  IF OLD.purchase_status = 'approved' AND NEW.purchase_status = 'approved'
     AND (NEW.purchase_price IS DISTINCT FROM OLD.purchase_price
          OR NEW.purchase_gst_pct IS DISTINCT FROM OLD.purchase_gst_pct) THEN
    RAISE EXCEPTION 'H Promise: the purchase price is locked after approval. Reopen the purchase first.'
      USING ERRCODE = 'HP001';
  END IF;
  IF OLD.sale_status = 'approved' AND NEW.sale_status = 'approved'
     AND NEW.selling_price IS DISTINCT FROM OLD.selling_price THEN
    RAISE EXCEPTION 'H Promise: the selling price is locked after approval. Reopen the sale first.'
      USING ERRCODE = 'HP001';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER tata_h_promise_price_lock
  BEFORE UPDATE ON public.tata_h_promise_vehicles
  FOR EACH ROW EXECUTE FUNCTION public.tata_h_promise_price_lock();

