-- ─────────────────────────────────────────────────────────────────────────────────────────────────
-- 3. Files
-- ─────────────────────────────────────────────────────────────────────────────────────────────────
-- A staged upload has attached_at NULL until the form that uses it is saved, in the same transaction. Replacing
-- a file marks the old row superseded — it is kept, so "who uploaded the PAN we approved against" stays answerable.
CREATE TABLE IF NOT EXISTS public.tata_h_promise_files (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  vehicle_id          uuid REFERENCES public.tata_h_promise_vehicles (id) ON DELETE RESTRICT,
  booking_id          uuid REFERENCES public.tata_h_promise_bookings (id) ON DELETE RESTRICT,
  kind                text NOT NULL,
  -- Object path in the PRIVATE tata-h-promise bucket. Never a public URL; read back through a short signed URL.
  storage_path        text NOT NULL UNIQUE,
  content_type        text NOT NULL,
  size_bytes          integer NOT NULL,
  sha256              text NOT NULL,
  original_name       text,
  source              text NOT NULL DEFAULT 'upload',                  -- upload | import
  -- For imported files: the Google Drive link the sheet held. Kept for traceability only; never served.
  legacy_url          text,
  uploaded_by         uuid REFERENCES public.users (id),
  uploaded_by_name    text NOT NULL,
  uploaded_at         timestamptz NOT NULL DEFAULT now(),
  attached_at         timestamptz,
  superseded_at       timestamptz,
  superseded_by       uuid REFERENCES public.tata_h_promise_files (id),
  CONSTRAINT tata_h_promise_files_size_positive CHECK (size_bytes > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS tata_h_promise_files_current_vehicle_kind
  ON public.tata_h_promise_files (vehicle_id, kind)
  WHERE attached_at IS NOT NULL AND superseded_at IS NULL AND booking_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS tata_h_promise_files_current_booking_kind
  ON public.tata_h_promise_files (booking_id, kind)
  WHERE attached_at IS NOT NULL AND superseded_at IS NULL AND booking_id IS NOT NULL;
-- Makes the import idempotent: the same Drive link is never copied twice for the same vehicle and slot.
CREATE UNIQUE INDEX IF NOT EXISTS tata_h_promise_files_import_key
  ON public.tata_h_promise_files (vehicle_id, kind, legacy_url) WHERE legacy_url IS NOT NULL;
CREATE INDEX IF NOT EXISTS tata_h_promise_files_vehicle_idx
  ON public.tata_h_promise_files (vehicle_id, kind, uploaded_at DESC);
CREATE INDEX IF NOT EXISTS tata_h_promise_files_staged_idx
  ON public.tata_h_promise_files (uploaded_by, uploaded_at) WHERE attached_at IS NULL;

-- ─────────────────────────────────────────────────────────────────────────────────────────────────
-- 4. Events — append-only
-- ─────────────────────────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.tata_h_promise_events (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- RESTRICT, not SET NULL: SET NULL is an UPDATE, which the append-only trigger refuses (see 0071). Vehicles
  -- are soft-deleted only, so this never blocks the app.
  vehicle_id      uuid REFERENCES public.tata_h_promise_vehicles (id) ON DELETE RESTRICT,
  subject         text NOT NULL DEFAULT 'vehicle',       -- vehicle | booking | option | setting | exchange_bonus
  subject_id      uuid,
  stock_no        integer,
  reg_no          text,
  action          text NOT NULL,
  from_status     text,
  to_status       text,
  actor_id        uuid REFERENCES public.users (id),
  actor_name      text NOT NULL,
  actor_role      text,
  remarks         text,
  -- {field: {from, to}}. Personal fields are written as {changed: true} — never the values.
  changes         jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS tata_h_promise_events_vehicle_idx
  ON public.tata_h_promise_events (vehicle_id, created_at DESC);
CREATE INDEX IF NOT EXISTS tata_h_promise_events_subject_idx
  ON public.tata_h_promise_events (subject, subject_id, created_at DESC);

