// ---------------------------------------------------------------------------
// Runner
// ---------------------------------------------------------------------------
async function main() {
  const databaseUrl = ddlDatabaseUrl()
  console.log('[vas-view] Connecting to database (session mode)...')

  const sql = postgres(databaseUrl, {
    ssl: { rejectUnauthorized: false },
    prepare: false,
    max: 1,
    idle_timeout: 5,
    connect_timeout: 30,
    connection: {
      application_name: 'refresh_platinum_vas_view',
      statement_timeout: 600_000,
    },
  })

  try {
    const steps = [
      { label: 'DROP am_platinum_vas_period_summary_v1', sql: DROP_VIEW },
      { label: 'CREATE am_platinum_vas_period_summary_v1', sql: CREATE_VIEW },
      { label: 'CREATE UNIQUE INDEX', sql: CREATE_UNIQUE_INDEX },
      { label: 'CREATE PERIOD INDEX', sql: CREATE_PERIOD_INDEX },
    ]

    for (const step of steps) {
      console.log(`[vas-view] → ${step.label}`)
      const t = Date.now()
      await sql.unsafe(step.sql)
      console.log(`[vas-view] ✓ done in ${Date.now() - t}ms`)
    }

    // Verify row count
    const rows = await sql`SELECT COUNT(*) AS total, COUNT(DISTINCT dealer_code) AS dealers FROM am_platinum_vas_period_summary_v1`
    console.log(`[vas-view] ✓ View contains ${rows[0].total} rows across ${rows[0].dealers} dealers`)
    console.log('[vas-view] ✅ All done — VAS materialized view refreshed successfully.')
  } finally {
    await sql.end()
  }
}

main().catch((error) => {
  console.error('[vas-view] ❌ Failed:', error.message || error)
  process.exit(1)
})
