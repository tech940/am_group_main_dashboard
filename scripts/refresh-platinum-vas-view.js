function ddlDatabaseUrl() {
  const raw = process.env.DATABASE_URL || process.env.DATABASE_DIRECT_URL || process.env.POSTGRES_URL
  if (!raw) throw new Error('DATABASE_URL is not configured')

  // pgbouncer (transaction mode, port 6543) does not support DDL.
  // Switch to session pooler (port 5432) for materialized view operations.
  const url = new URL(raw)
  if (url.port === '6543' || url.searchParams.get('pgbouncer') === 'true') {
    url.port = '5432'
    url.searchParams.delete('pgbouncer')
  }
  return url.toString()
}

